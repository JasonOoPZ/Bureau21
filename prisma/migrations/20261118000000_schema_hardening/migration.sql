-- -------------------------------------------------------------------------
-- 0. Pre-flight. These run before anything is changed and stop the migration
--    with a readable message when the data needs a human decision first.
-- -------------------------------------------------------------------------

-- 0a. Duplicate callsigns (ignoring case and extra spaces). Renaming a player
--     is not something a migration should decide. Find them with
--     scripts/audit/10_duplicate_callsigns.sql and resolve them with
--     scripts/audit/fixes/rename_duplicate_callsigns.sql.
DO $$
DECLARE
  dup_count integer;
  dup_sample text;
BEGIN
  SELECT count(*), string_agg(key, ', ' ORDER BY key)
    INTO dup_count, dup_sample
  FROM (
    SELECT lower(regexp_replace(btrim("callsign"), '\s+', ' ', 'g')) AS key
    FROM "PilotState"
    GROUP BY 1
    HAVING count(*) > 1
    ORDER BY 1
    LIMIT 20
  ) d;

  IF dup_count > 0 THEN
    RAISE EXCEPTION
      'schema_hardening pre-flight failed: % duplicate callsign(s), for example: %. Nothing was changed. Run scripts/audit/10_duplicate_callsigns.sql, resolve them, then re-run the migration.',
      dup_count, dup_sample;
  END IF;
END $$;

-- 0b. Balances that are already negative would make the CHECK constraints
--     below fail half way with a less helpful message. Find them with
--     scripts/audit/04_negative_balances.sql.
DO $$
DECLARE
  bad_count integer;
BEGIN
  SELECT count(*) INTO bad_count
  FROM "PilotState"
  WHERE "credits" < 0 OR "creditsBank" < 0 OR "tokens" < 0 OR "ore" < 0
     OR "herbs" < 0 OR "fish" < 0 OR "fuel" < 0 OR "hull" < 0
     OR "motivation" < 0 OR "unspentPoints" < 0 OR "loanAmount" < 0
     OR "bondAmount" < 0 OR "xp" < 0 OR "gymEnergy" < 0 OR "lifeForce" < 0;

  IF bad_count > 0 THEN
    RAISE EXCEPTION
      'schema_hardening pre-flight failed: % pilot(s) hold a negative balance. Nothing was changed. Run scripts/audit/04_negative_balances.sql, correct them, then re-run the migration.',
      bad_count;
  END IF;

  SELECT (SELECT count(*) FROM "GameGlobal" WHERE "bankTreasury" < 0)
       + (SELECT count(*) FROM "Syndicate" WHERE "treasury" < 0)
    INTO bad_count;

  IF bad_count > 0 THEN
    RAISE EXCEPTION
      'schema_hardening pre-flight failed: % treasury row(s) are negative. Nothing was changed. Run scripts/audit/04_negative_balances.sql, correct them, then re-run the migration.',
      bad_count;
  END IF;
END $$;

