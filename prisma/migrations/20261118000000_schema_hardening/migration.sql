-- 4a. Keep the unique callsign key in step with the callsign on every write,
--     whatever wrote it: the app (which also sets it), an older deployment
--     still running during the rollout, or a maintenance script.
CREATE FUNCTION "PilotState_sync_callsignLower"() RETURNS trigger AS $$
BEGIN
  NEW."callsignLower" := lower(regexp_replace(btrim(NEW."callsign"), '\s+', ' ', 'g'));
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "PilotState_callsignLower_sync"
BEFORE INSERT OR UPDATE OF "callsign", "callsignLower" ON "PilotState"
FOR EACH ROW EXECUTE FUNCTION "PilotState_sync_callsignLower"();

-- 4b. At most one open crash run per pilot. This is what stops two parallel
