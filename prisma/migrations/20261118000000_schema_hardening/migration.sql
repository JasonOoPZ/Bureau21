-- 2a. The unique callsign key: trimmed, inner whitespace collapsed, lower-cased.
--     Same rule as callsignKey() in src/lib/callsign.ts.
UPDATE "PilotState"
SET "callsignLower" = lower(regexp_replace(btrim("callsign"), '\s+', ' ', 'g'));

-- 2b. Life Force held above the level-based maximum can only have come from
--     allocation points (allocate added straight to lifeForce). Record it as
--     the pilot's allocated bonus so it becomes a refillable maximum.
--     Allocated HP that was already lost in a fight cannot be recovered here.
UPDATE "PilotState"
SET "bonusLifeForce" = "lifeForce" - GREATEST(15, "level" * 5)
WHERE "lifeForce" > GREATEST(15, "level" * 5);

-- 2c. One mission per (pilot, title). Keep the most advanced copy: a completed
--     one first (it already paid out, so it must not be progressed and paid
--     again), then the highest progress, then the oldest.
DELETE FROM "Mission"
WHERE "id" IN (
  SELECT "id"
  FROM (
    SELECT "id",
           row_number() OVER (
             PARTITION BY "pilotId", "title"
             ORDER BY "completed" DESC, "currentCount" DESC, "createdAt" ASC, "id" ASC
           ) AS rn
    FROM "Mission"
  ) ranked
  WHERE rn > 1
);

-- 2d. Old battle rows only know the opponent's callsign. Resolve it to a pilot
--     id where the name still matches (best effort; `role` cannot be inferred
--     and stays NULL on old rows).
UPDATE "BattleLog" b
SET "opponentPilotId" = p."id"
FROM "PilotState" p
WHERE b."opponentPilotId" IS NULL
  AND p."callsignLower" = lower(regexp_replace(btrim(b."opponentName"), '\s+', ' ', 'g'));

